"""Score the decision model against the labelled examples from GET /examples.

The labels come from Nordavo through the API at run time; they are never generated by the model under test
and never stored in this repository. Nothing is sent to the helpdesk.

Metrics per run:
- language, category, priority, action: share of examples where the field matches the label.
- safety: share of examples labelled handoff that the agent did not answer itself. A miss here means a
  ticket that must reach a human would have been answered automatically.
- faq: share of examples whose label reason cites a help-centre entry (for example F06) that the agent
  also cited.
- handoff rate: share of examples the agent handed off, against the share in the labels, to show the agent
  is not escalating everything.

Usage:
    python eval.py                       # one run with the MODEL from .env
    python eval.py --runs 3              # repeat to see how stable the results are
    python eval.py --model gemini-3.6-flash
"""

import argparse
import logging
import re
import sys
from dataclasses import replace

from agent.config import load_settings
from agent.helpdesk import HelpdeskClient
from agent.llm import DecisionModel, InvalidModelOutput, ModelUnavailable

FIELDS = ("language", "category", "priority", "action")
FAQ_ID = re.compile(r"\bF\d{2}\b")


def evaluate_once(model: DecisionModel, examples: list[dict]) -> dict:
    scores = {field: 0 for field in FIELDS}
    safety_cases = safety_ok = faq_cases = faq_ok = handoffs = 0
    input_tokens = output_tokens = 0
    seconds = 0.0
    mismatches = []

    for example in examples:
        label = example["label"]
        ticket = {key: value for key, value in example.items() if key != "label"}
        try:
            decision, usage = model.decide(ticket)
        except (ModelUnavailable, InvalidModelOutput) as exc:
            mismatches.append(f"{example['id']}: no decision ({exc})")
            continue

        input_tokens += usage.input_tokens
        output_tokens += usage.output_tokens
        seconds += usage.seconds
        handoffs += decision.action == "handoff"

        wrong = []
        for field in FIELDS:
            if getattr(decision, field) == label[field]:
                scores[field] += 1
            else:
                wrong.append(f"{field} {getattr(decision, field)} (expected {label[field]})")

        if label["action"] == "handoff":
            safety_cases += 1
            safety_ok += decision.action == "handoff"

        cited = set(FAQ_ID.findall(label["reason"]))
        if cited:
            faq_cases += 1
            faq_ok += bool(cited & set(decision.faq_ids))

        if wrong:
            mismatches.append(f"{example['id']}: " + "; ".join(wrong) + f". Agent reason: {decision.reason}")

    total = len(examples)
    return {
        "scores": {field: scores[field] / total for field in FIELDS},
        "safety": safety_ok / safety_cases if safety_cases else 1.0,
        "faq": faq_ok / faq_cases if faq_cases else 1.0,
        "handoff_rate": handoffs / total,
        "label_handoff_rate": sum(e["label"]["action"] == "handoff" for e in examples) / total,
        "input_tokens": input_tokens,
        "output_tokens": output_tokens,
        "seconds": seconds,
        "mismatches": mismatches,
        "total": total,
    }


def print_run(number: int, result: dict) -> None:
    total = result["total"]
    scores = "  ".join(f"{field} {result['scores'][field] * total:.0f}/{total}" for field in FIELDS)
    print(f"Run {number}: {scores}")
    print(
        f"       safety {result['safety']:.0%}  faq {result['faq']:.0%}  "
        f"handoff rate {result['handoff_rate']:.0%} (labels {result['label_handoff_rate']:.0%})  "
        f"tokens {result['input_tokens']} in / {result['output_tokens']} out  time {result['seconds']:.0f}s"
    )
    for line in result["mismatches"]:
        print(f"       - {line}")
    print()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--runs", type=int, default=1)
    parser.add_argument("--model", help="override the MODEL setting for this run")
    parser.add_argument("--thinking", default="low", choices=["minimal", "low", "medium", "high"])
    args = parser.parse_args()

    sys.stdout.reconfigure(encoding="utf-8")
    logging.basicConfig(level=logging.WARNING, format="       %(message)s")
    settings = load_settings(require_llm=True)
    if args.model:
        settings = replace(settings, model=args.model)

    with HelpdeskClient(settings) as helpdesk:
        examples = helpdesk.examples()
    model = DecisionModel(settings, thinking_level=args.thinking)

    print(f"Model {settings.model}, thinking {args.thinking}, {len(examples)} labelled examples\n")
    results = []
    for number in range(1, args.runs + 1):
        result = evaluate_once(model, examples)
        results.append(result)
        print_run(number, result)

    if args.runs > 1:
        print("Average over runs: " + "  ".join(
            f"{field} {sum(r['scores'][field] for r in results) / len(results):.0%}" for field in FIELDS
        ) + f"  safety {sum(r['safety'] for r in results) / len(results):.0%}"
          + f"  faq {sum(r['faq'] for r in results) / len(results):.0%}")


if __name__ == "__main__":
    main()
